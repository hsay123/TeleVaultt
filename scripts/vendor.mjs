import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const root = process.cwd();
const vendor = join(root, 'assets', 'vendor');

const files = [
  ['node_modules/lenis/dist/lenis.min.js', 'lenis/lenis.min.js'],
  ['node_modules/lenis/dist/lenis.css', 'lenis/lenis.css'],
  ['node_modules/lenis/LICENSE', 'lenis/LICENSE'],
  ['node_modules/gsap/dist/gsap.min.js', 'gsap/gsap.min.js'],
  ['node_modules/gsap/dist/ScrollTrigger.min.js', 'gsap/ScrollTrigger.min.js'],
  ['node_modules/gsap/README.md', 'gsap/README.md'],
  ['node_modules/lucide/LICENSE', 'lucide/LICENSE'],
];

for (const [from, to] of files) {
  const target = join(vendor, to);
  await mkdir(dirname(target), { recursive: true });
  await copyFile(join(root, from), target);
  console.log(`copied ${to}`);
}

/* -------------------------------------------------------------------------- */
/* Lucide subset                                                              */
/* -------------------------------------------------------------------------- */
/*
 * The full Lucide UMD bundle is ~115 KB because it ships every icon. The site
 * uses a few dozen, so `npm run vendor` builds a bundle that contains only the
 * icons referenced by `data-lucide` in the HTML and JS. This keeps the icons
 * available at first paint without paying for the rest of the icon set.
 */

const require = createRequire(import.meta.url);
const lucide = require(join(root, 'node_modules/lucide/dist/umd/lucide.min.js'));

const pascal = (name) =>
  name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

const sources = ['index.html', 'contribute.html', '404.html', 'script.js'];
const names = new Set();

for (const file of sources) {
  const source = await readFile(join(root, file), 'utf8');
  for (const match of source.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(match[1]);
}

const used = [...names].sort();
const missing = used.filter((name) => !lucide.icons[pascal(name)]);
if (missing.length) throw new Error(`Unknown Lucide icons: ${missing.join(', ')}`);

const entries = used.map((name) => `    ${pascal(name)}: ${JSON.stringify(lucide.icons[pascal(name)])},`);

const subset = `/**
 * @license lucide v${JSON.parse(await readFile(join(root, 'node_modules/lucide/package.json'), 'utf8')).version} - ISC
 *
 * Generated by \`npm run vendor\`. Do not edit by hand.
 * Contains only the icons referenced by data-lucide in this site.
 */

(function (global) {
  'use strict';

  var SVG = 'http://www.w3.org/2000/svg';
  var DEFAULTS = {
    xmlns: SVG,
    width: 24,
    height: 24,
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': 2,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
  };

  var ICONS = {
${entries.join('\n')}
  };

  function pascal(name) {
    return name
      .split('-')
      .map(function (part) {
        return part.charAt(0).toUpperCase() + part.slice(1);
      })
      .join('');
  }

  function mergeClasses() {
    var classes = [];
    for (var i = 0; i < arguments.length; i++) {
      var value = arguments[i];
      if (value) classes.push(value);
    }
    return classes.length ? classes.join(' ') : undefined;
  }

  function replace(placeholder, icons) {
    var name = placeholder.getAttribute('data-lucide');
    if (name == null) return;

    var iconNode = icons[pascal(name)];
    if (!iconNode) return;

    var attrs = {};
    var source = placeholder.attributes;
    for (var i = 0; i < source.length; i++) attrs[source[i].name] = source[i].value;

    var hasA11y = Object.keys(attrs).some(function (key) {
      return key === 'role' || key.indexOf('aria-') === 0;
    });

    var svg = document.createElementNS(SVG, 'svg');
    var merged = Object.assign({}, DEFAULTS, { 'data-lucide': name }, hasA11y ? null : { 'aria-hidden': 'true' }, attrs);
    merged['class'] = mergeClasses('lucide', 'lucide-' + name, attrs['class']);

    Object.keys(merged).forEach(function (key) {
      if (merged[key] !== undefined) svg.setAttribute(key, merged[key]);
    });

    iconNode.forEach(function (child) {
      var element = document.createElementNS(SVG, child[0]);
      Object.keys(child[1]).forEach(function (key) {
        element.setAttribute(key, child[1][key]);
      });
      svg.appendChild(element);
    });

    placeholder.parentNode.replaceChild(svg, placeholder);
  }

  function createIcons(options) {
    var opts = options || {};
    var icons = opts.icons || ICONS;
    var root = opts.root || document;
    var nameAttr = opts.nameAttr || 'data-lucide';
    var placeholders = Array.prototype.slice.call(root.querySelectorAll('[' + nameAttr + ']'));
    placeholders.forEach(function (placeholder) {
      replace(placeholder, icons);
    });
  }

  global.lucide = { createIcons: createIcons, icons: ICONS };
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

await writeFile(join(vendor, 'lucide', 'lucide-subset.js'), subset);
console.log(`wrote lucide/lucide-subset.js (${used.length} icons)`);

